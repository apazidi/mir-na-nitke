import assert from 'node:assert/strict';
import {inspect} from './browser.mjs';
await inspect({name:process.env.EVIDENCE_NAME??'director-v1',record:true},async({page,snapshot,points,capture,pass,errors})=>{
 const p=await points(),at=(x,y)=>({x:p.center.x+x*p.scale+(p.gripOffset?.x??0),y:p.center.y+y*p.scale+(p.gripOffset?.y??0)});
 const initial=await capture('00-start');
 await pass('01-empty',[at(-1.65,-1.6),at(-1.45,-1.6),at(-1.25,-1.6)]);
 assert.deepEqual((await snapshot()).lengths,initial.state.lengths,'empty movement cannot manufacture');
 const held=at(-.92,0);await page.mouse.move(held.x,held.y);await page.mouse.down();await page.waitForTimeout(650);await capture('02-stationary');await page.mouse.up();
 assert.deepEqual((await snapshot()).lengths,initial.state.lengths,'stationary holding cannot cut');
 const leftPath=[at(-.92,-.36),at(-.92,-.18),at(-.92,0),at(-.92,.18),at(-.92,.34)];
 const left=await pass('03-left',leftPath);
 assert.ok(left.state.changedFibers>0&&left.state.changedFibers<initial.state.lengths.length*.3,'small cut must remain local');
 await pass('04-same-empty-path',leftPath);
 assert.deepEqual((await snapshot()).lengths,left.state.lengths,'cut does not progress through already empty space');
 const right=await pass('05-right',[at(.89,-.30),at(.89,-.10),at(.89,.10),at(.89,.30)]);
 assert.notDeepEqual(right.state.lengths,left.state.lengths,'different side has its own material change');
 const deep=await pass('06-deep',[at(.40,-.42),at(.40,-.20),at(.40,.02),at(.40,.24),at(.40,.42)]);
 assert.notDeepEqual(deep.state.lengths,right.state.lengths,'deep mistake must exist in material');
 await page.locator('#undo').click();const restored=await capture('07-undo-deep');
 assert.deepEqual(restored.state.lengths,right.state.lengths,'undo restores exactly the last pass');
 await page.locator('#finish').click();const done=await capture('08-own-form');
 assert.equal(done.state.finished,true);assert.deepEqual(done.state.lengths,right.state.lengths,'finish cannot improve the shape');
 await page.reload();await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
 const reopened=await capture('09-reopened');assert.deepEqual(reopened.state.lengths,right.state.lengths);assert.equal(reopened.state.finished,true);
 await page.locator('#finish').click();
 await pass('10-second-profile',[at(-.72,-.7),at(-.35,-.7),at(0,-.7),at(.35,-.7),at(.72,-.7)]);
 await page.locator('#finish').click();const second=await capture('11-second-own-form');
 assert.notDeepEqual(second.state.lengths,done.state.lengths,'another profile is retained, not swapped to a shared final');
 assert.deepEqual(errors,[]);console.log('Observed real local cuts, mistake/undo, two retained profiles and reload. Enjoyment and visual quality require independent review.');
});
